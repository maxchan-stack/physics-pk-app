interface RawGsatQuestionInput {
  year: 110 | 111 | 112 | 113 | 114 | 115;
  chapterId: GsatChapterKey;
  difficulty: 1 | 2 | 3;
  isConceptual?: boolean;
  conceptId?: string;
  stem: string;
  options: [string, string, string, string];
  correctIndex: number;
  shortExplanation: string;
  keyFormula: string;
  detailedSteps: string;
  commonTrap: string;
}

/**
 * 將歷屆學測精簡資料統一映射為標準 PhysicsQuestion 格式
 */
function buildGsatQuestions(items: RawGsatQuestionInput[]): PhysicsQuestion[] {
  return items.map((item, idx) => {
    const meta = GSAT_CHAPTER_META[item.chapterId];
    return {
      id: `q-gsat-${item.year}-${idx + 1}`,
      chapterId: item.chapterId,
      chapterCode: meta.code,
      chapterTitle: meta.title,
      grade: meta.grade,
      difficulty: item.difficulty,
      gsatYear: item.year,
      isConceptual: item.isConceptual ?? false,
      stem: `【${item.year}學測】${item.stem}`,
      options: item.options,
      correctIndex: item.correctIndex,
      shortExplanation: item.shortExplanation,
      keyFormula: item.keyFormula,
      detailedSteps: item.detailedSteps,
      commonTrap: item.commonTrap,
      conceptId: item.conceptId ?? meta.defaultConceptId,
    };
  });
}

